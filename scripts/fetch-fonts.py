#!/usr/bin/env python3
"""Self-host the theme's Google Fonts.

heritage.css used to open with an @import from fonts.googleapis.com. That is
the worst way to load a font — the browser has to fetch and parse the
stylesheet before it even discovers the font request, serialising two
round-trips onto the critical path — and it hands every visitor's IP address
to a third party before they have consented to anything.

This downloads the woff2 files once into assets/fonts/ and writes
assets/css/fonts.css with the matching @font-face rules.

    python3 scripts/fetch-fonts.py

Both families are open source (SIL Open Font License), so redistributing the
files with the theme is fine.
"""

from __future__ import annotations

import pathlib
import re
import sys

import requests

FAMILIES = (
    "Cormorant+Garamond:ital,wght@0,300;0,400;0,500;0,600;1,300;1,400"
    "&family=EB+Garamond:ital,wght@0,400;0,500;1,400"
)
# The theme is Dutch and English; the other subsets Google splits out
# (cyrillic, greek, vietnamese) would never be requested.
KEEP_SUBSETS = ("latin", "latin-ext")

# A modern UA is what makes Google return woff2 rather than older formats.
UA = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) "
    "Chrome/126.0.0.0 Safari/537.36"
)

ROOT = pathlib.Path(__file__).resolve().parent.parent
THEME = ROOT / "wp-content/themes/maison-opus"
FONT_DIR = THEME / "assets/fonts"
CSS_OUT = THEME / "assets/css/fonts.css"

HEADER = """/* Self-hosted webfonts — generated by scripts/fetch-fonts.py, do not edit.
   Replaces an @import from fonts.googleapis.com: no third-party request, no
   visitor IP sent to Google, and one less round-trip before text can paint.
   Cormorant Garamond and EB Garamond are both SIL Open Font License. */
"""


def main() -> int:
    url = f"https://fonts.googleapis.com/css2?family={FAMILIES}&display=swap"
    css = requests.get(url, headers={"User-Agent": UA}, timeout=30).text

    FONT_DIR.mkdir(parents=True, exist_ok=True)
    blocks, kept, skipped = [], 0, 0

    # Google labels each block with the subset in a comment directly above it;
    # pair the two so the label belongs to the block it precedes.
    faces = re.findall(r"/\*\s*([a-z-]+)\s*\*/\s*@font-face\s*\{(.*?)\}", css, re.S)
    if not faces:
        print("Could not parse the Google Fonts response.", file=sys.stderr)
        return 1

    for subset, chunk in faces:
        if subset not in KEEP_SUBSETS:
            skipped += 1
            continue

        family = re.search(r"font-family:\s*'([^']+)'", chunk).group(1)
        style = re.search(r"font-style:\s*(\w+)", chunk).group(1)
        weight = re.search(r"font-weight:\s*(\d+)", chunk).group(1)
        remote = re.search(r"url\((https://[^)]+\.woff2)\)", chunk).group(1)
        urange = re.search(r"unicode-range:\s*([^;]+);", chunk)

        name = f"{family.lower().replace(' ', '-')}-{weight}-{style}-{subset}.woff2"
        target = FONT_DIR / name
        if not target.exists():
            target.write_bytes(
                requests.get(remote, headers={"User-Agent": UA}, timeout=30).content
            )
        kept += 1

        rule = [
            "@font-face {",
            f"  font-family: '{family}';",
            f"  font-style: {style};",
            f"  font-weight: {weight};",
            "  font-display: swap;",
            f"  src: url('../fonts/{name}') format('woff2');",
        ]
        if urange:
            rule.append(f"  unicode-range: {urange.group(1).strip()};")
        rule.append("}")
        blocks.append("\n".join(rule))

    CSS_OUT.write_text(HEADER + "\n" + "\n\n".join(blocks) + "\n", encoding="utf-8")

    total = sum(f.stat().st_size for f in FONT_DIR.glob("*.woff2"))
    print(f"{kept} faces kept, {skipped} skipped (other subsets)")
    print(f"{FONT_DIR.relative_to(ROOT)}  {total // 1024} KB total")
    print(f"{CSS_OUT.relative_to(ROOT)}  written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
