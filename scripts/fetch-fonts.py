#!/usr/bin/env python3
"""Self-host the theme's Google Fonts.

heritage.css used to open with an @import from fonts.googleapis.com. That is
the worst way to load a font — the browser has to fetch and parse the
stylesheet before it even discovers the font request, serialising two
round-trips onto the critical path — and it hands every visitor's IP address
to a third party before they have consented to anything.

This downloads the woff2 files once into assets/fonts/ and writes
assets/css/fonts.css with the matching @font-face rules.

The faces are emitted `font-display: optional`, not `swap`. With swap the
browser paints a fallback and then re-renders in the real face, which moves
the page — visibly, on the homepage hero. With optional it gives the font a
short window (it is same-origin and preloaded, so it normally wins) and
otherwise keeps the fallback for that page load without ever swapping. The
cost is that a slow first visit renders in Georgia; the gain is that nothing
ever jumps.

    python3 scripts/fetch-fonts.py          # heritage → assets/css/fonts.css
    python3 scripts/fetch-fonts.py v2       # v2 skin  → assets/css/fonts-v2.css

All families are open source (SIL Open Font License), so redistributing the
files with the theme is fine.
"""

from __future__ import annotations

import pathlib
import re
import sys

import requests
from fontTools.ttLib import TTFont

# The theme is Dutch and English; the other subsets Google splits out
# (cyrillic, greek, vietnamese) would never be requested.
KEEP_SUBSETS = ("latin", "latin-ext")

# A modern UA is what makes Google return woff2 rather than older formats.
UA = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) "
    "Chrome/126.0.0.0 Safari/537.36"
)

ROOT = pathlib.Path(__file__).resolve().parent.parent
THEME = ROOT / "wp-content/themes/maison-opus"
FONT_DIR = THEME / "assets/fonts"
HEADER = """/* Self-hosted webfonts — generated by scripts/fetch-fonts.py, do not edit.
   Replaces an @import from fonts.googleapis.com: no third-party request, no
   visitor IP sent to Google, and one less round-trip before text can paint.
   {names}: SIL Open Font License. */
"""

# Georgia leads the serif fallback stacks, Arial the sans ones; both ship on
# Windows, macOS and iOS. "avg" is xAvgCharWidth from their OS/2 tables.
GEORGIA = {"upm": 2048, "avg": 1189}
ARIAL = {"upm": 2048, "avg": 1187}  # via Liberation Sans, metric-compatible

# Per skin: Google Fonts families, output stylesheet, fallback reference
# metrics and the locals to try, in order, for the metric-matched fallback.
SKINS = {
    "heritage": {
        "families": "Cormorant+Garamond:ital,wght@0,300;0,400;0,500;0,600;1,300;1,400"
        "&family=EB+Garamond:ital,wght@0,400;0,500;1,400",
        "css": "fonts.css",
        "ref": GEORGIA,
        "locals": ("Georgia", "Times New Roman", "Liberation Serif", "Nimbus Roman"),
    },
    "v2": {
        "families": "Jost:wght@300;400;500;600;700&family=Marcellus",
        "css": "fonts-v2.css",
        "ref": ARIAL,
        "locals": ("Arial", "Helvetica", "Liberation Sans", "Nimbus Sans"),
        "serif": {"Marcellus"},  # titles; falls back to Georgia, not Arial
    },
}


def fallback_face(family: str, sample: pathlib.Path, ref: dict, locals_: tuple) -> str:
    """A fallback @font-face whose text occupies the same box as the webfont.

    Without this the browser paints the fallback, then reflows the page when the
    real face arrives — the visible jump on first load. size-adjust scales the
    fallback so its average glyph width matches, and the ascent/descent
    overrides make the line box identical.
    """
    font = TTFont(sample)
    upm = font["head"].unitsPerEm
    hhea = font["hhea"]
    avg = font["OS/2"].xAvgCharWidth

    size_adjust = (avg / upm) / (ref["avg"] / ref["upm"])
    src = ", ".join(f"local('{name}')" for name in locals_)

    return "\n".join(
        [
            f"/* Metric-matched fallback for {family}, so the swap moves nothing. */",
            "@font-face {",
            f"  font-family: '{family} Fallback';",
            f"  src: {src};",
            f"  size-adjust: {size_adjust * 100:.2f}%;",
            f"  ascent-override: {hhea.ascent / upm / size_adjust * 100:.2f}%;",
            f"  descent-override: {abs(hhea.descent) / upm / size_adjust * 100:.2f}%;",
            f"  line-gap-override: {hhea.lineGap / upm / size_adjust * 100:.2f}%;",
            "}",
        ]
    )


def main() -> int:
    skin = sys.argv[1] if len(sys.argv) > 1 else "heritage"
    if skin not in SKINS:
        print(f"Unknown skin {skin!r}; pick one of {', '.join(SKINS)}", file=sys.stderr)
        return 1
    cfg = SKINS[skin]
    css_out = THEME / "assets/css" / cfg["css"]
    url = f"https://fonts.googleapis.com/css2?family={cfg['families']}&display=swap"
    # (the &display on the request only affects Google's own CSS, which we
    # rewrite below; ours is emitted as `optional`.)
    css = requests.get(url, headers={"User-Agent": UA}, timeout=30).text

    FONT_DIR.mkdir(parents=True, exist_ok=True)
    blocks, kept, skipped = [], 0, 0

    # Google labels each block with the subset in a comment directly above it;
    # pair the two so the label belongs to the block it precedes.
    faces = re.findall(r"/\*\s*([a-z-]+)\s*\*/\s*@font-face\s*\{(.*?)\}", css, re.S)
    if not faces:
        print("Could not parse the Google Fonts response.", file=sys.stderr)
        return 1

    # A variable family (Jost) comes back as one file per subset that Google
    # repeats for every weight asked for. Group the blocks by file so it is
    # stored and declared once, with a weight range, instead of once per weight.
    groups: dict[str, dict] = {}
    for subset, chunk in faces:
        if subset not in KEEP_SUBSETS:
            skipped += 1
            continue

        remote = re.search(r"url\((https://[^)]+\.woff2)\)", chunk).group(1)
        weight = int(re.search(r"font-weight:\s*(\d+)", chunk).group(1))
        if remote in groups:
            groups[remote]["weights"].append(weight)
            continue
        urange = re.search(r"unicode-range:\s*([^;]+);", chunk)
        groups[remote] = {
            "subset": subset,
            "family": re.search(r"font-family:\s*'([^']+)'", chunk).group(1),
            "style": re.search(r"font-style:\s*(\w+)", chunk).group(1),
            "weights": [weight],
            "urange": urange.group(1).strip() if urange else None,
        }

    for remote, g in groups.items():
        lo, hi = min(g["weights"]), max(g["weights"])
        weight = f"{lo}" if lo == hi else f"{lo} {hi}"
        span = f"{lo}" if lo == hi else f"{lo}-{hi}"
        name = f"{g['family'].lower().replace(' ', '-')}-{span}-{g['style']}-{g['subset']}.woff2"
        target = FONT_DIR / name
        if not target.exists():
            target.write_bytes(
                requests.get(remote, headers={"User-Agent": UA}, timeout=30).content
            )
        kept += 1

        rule = [
            "@font-face {",
            f"  font-family: '{g['family']}';",
            f"  font-style: {g['style']};",
            f"  font-weight: {weight};",
            "  font-display: optional;",
            f"  src: url('../fonts/{name}') format('woff2');",
        ]
        if g["urange"]:
            rule.append(f"  unicode-range: {g['urange']};")
        rule.append("}")
        blocks.append("\n".join(rule))

    fallbacks = []
    for family in sorted({b.split("'")[1] for b in blocks if "font-family:" in b}):
        stem = family.lower().replace(" ", "-")
        sample = next(FONT_DIR.glob(f"{stem}-*-normal-latin.woff2"), None)
        if sample:
            if family in cfg.get("serif", ()):
                ref, locals_ = GEORGIA, SKINS["heritage"]["locals"]
            else:
                ref, locals_ = cfg["ref"], cfg["locals"]
            fallbacks.append(fallback_face(family, sample, ref, locals_))

    names = " and ".join(sorted({b.split("'")[1] for b in blocks}))
    css_out.write_text(
        HEADER.format(names=names) + "\n" + "\n\n".join(fallbacks + blocks) + "\n",
        encoding="utf-8",
    )

    total = sum(f.stat().st_size for f in FONT_DIR.glob("*.woff2"))
    print(f"{kept} faces kept, {skipped} skipped (other subsets)")
    print(f"{FONT_DIR.relative_to(ROOT)}  {total // 1024} KB total")
    print(f"{css_out.relative_to(ROOT)}  written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
